"""Pydantic schemas for Question Answering and Citation verification.

Defines schemas for:
- AskRequest: User query, retrieval bounds, and optional document filtering.
- CitationSourceItem: Strongly-typed source chunk attribution.
- ValidatedCitation: Explicit citation link between answer claim and source chunk.
- AskResponse: Complete grounded answer, sources, citations, and execution telemetry.
"""

import uuid

from pydantic import BaseModel, ConfigDict, Field


class AskRequest(BaseModel):
    """Request payload for SLM-powered grounded answer generation."""

    model_config = ConfigDict(extra="forbid")

    question: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="User question to answer using grounded document retrieval",
        examples=["How does connection pooling reduce database overhead?"],
    )
    limit: int = Field(
        default=5,
        ge=1,
        le=20,
        description="Maximum number of context chunks to retrieve for evidence",
    )
    document_id: uuid.UUID | None = Field(
        default=None,
        description="Optional filter to scope retrieval to a single document UUID",
    )


class CitationSourceItem(BaseModel):
    """Representation of an actual retrieved chunk supplied as evidence."""

    source_id: str = Field(
        ...,
        description="Application-assigned evidence token (e.g. '[source_1]')",
    )
    chunk_id: uuid.UUID = Field(
        ...,
        description="Database UUID of the retrieved document chunk",
    )
    document_id: uuid.UUID = Field(
        ...,
        description="Database UUID of the parent document",
    )
    filename: str = Field(
        ...,
        description="Original document filename",
    )
    chunk_index: int = Field(
        ...,
        description="Zero-based sequential index of the chunk in the document",
    )
    page_number: int | None = Field(
        default=None,
        description="1-based source page number where chunk text appears (if available)",
    )
    content: str = Field(
        ...,
        description="Text content of the retrieved chunk",
    )
    similarity_score: float = Field(
        ...,
        description="Cosine similarity score against the user question (0.0 to 1.0)",
    )


class ValidatedCitation(BaseModel):
    """A citation verified to exist within the retrieved evidence set."""

    source_id: str = Field(
        ...,
        description="Cited source identifier (e.g. '[source_1]')",
    )
    chunk_id: uuid.UUID = Field(
        ...,
        description="UUID of the corresponding retrieved chunk",
    )
    filename: str = Field(
        ...,
        description="Filename of the cited document",
    )
    page_number: int | None = Field(
        default=None,
        description="Page number of the cited passage",
    )


class GenerationTelemetry(BaseModel):
    """Safe performance and usage telemetry for the generation request."""

    provider: str = Field(..., description="Provider backend used (e.g. 'fake', 'azure')")
    model_name: str = Field(..., description="Model identifier used for generation")
    retrieval_latency_ms: float = Field(
        ...,
        description="Time taken to embed query and search pgvector",
    )
    generation_latency_ms: float = Field(..., description="Time taken for SLM inference")
    retrieved_chunk_count: int = Field(..., description="Number of candidate chunks retrieved")
    used_chunk_count: int = Field(..., description="Number of chunks fitted into the prompt budget")
    prompt_tokens: int | None = Field(default=None, description="Tokens consumed by prompt")
    completion_tokens: int | None = Field(default=None, description="Tokens generated in answer")
    total_tokens: int | None = Field(default=None, description="Total tokens consumed")


class AskResponse(BaseModel):
    """Structured response for grounded question answering."""

    question: str = Field(..., description="Normalized user question")
    answer: str = Field(..., description="Grounded answer text generated by the model")
    abstained: bool = Field(
        default=False,
        description="Whether the system abstained from answering due to insufficient evidence",
    )
    sources: list[CitationSourceItem] = Field(
        default_factory=list,
        description="Retrieved source chunks supplied to the model as context",
    )
    citations: list[ValidatedCitation] = Field(
        default_factory=list,
        description="Citations extracted from the answer and verified against retrieved sources",
    )
    telemetry: GenerationTelemetry = Field(
        ...,
        description="Execution metrics and latency breakdown",
    )
