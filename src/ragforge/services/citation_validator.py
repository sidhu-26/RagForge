"""Citation extraction, verification, and sanitization for RAG answers.

Extracts source references (e.g. '[source_1]') from generated answer text,
validates them against the actual retrieved context chunks for the request,
and strips hallucinated or invalid citation markers.
"""

import re
from dataclasses import dataclass

from ragforge.schemas.ask import CitationSourceItem, ValidatedCitation

# Matches citation patterns like [source_1], [source_12], etc.
CITATION_PATTERN = re.compile(r"\[source_(\d+)\]")


@dataclass
class CitationValidationResult:
    """Result of citation validation."""

    cleaned_answer: str
    validated_citations: list[ValidatedCitation]
    invalid_source_ids: list[str]
    has_valid_citations: bool


def validate_and_sanitize_citations(
    raw_answer: str,
    valid_sources: list[CitationSourceItem],
) -> CitationValidationResult:
    """Validate citations against retrieved sources and sanitize invalid citations.

    Args:
        raw_answer: The raw text generated by the language model.
        valid_sources: The list of CitationSourceItem objects included in the prompt.

    Returns:
        CitationValidationResult: Cleaned answer text, validated citations, and dropped IDs.
    """
    # Build fast lookup map: "[source_1]" -> CitationSourceItem
    source_map: dict[str, CitationSourceItem] = {src.source_id: src for src in valid_sources}

    found_matches = CITATION_PATTERN.findall(raw_answer)
    validated_citations: list[ValidatedCitation] = []
    invalid_ids: list[str] = []
    seen_valid_ids: set[str] = set()

    for num_str in found_matches:
        candidate_id = f"[source_{num_str}]"
        if candidate_id in source_map:
            if candidate_id not in seen_valid_ids:
                seen_valid_ids.add(candidate_id)
                src = source_map[candidate_id]
                validated_citations.append(
                    ValidatedCitation(
                        source_id=src.source_id,
                        chunk_id=src.chunk_id,
                        filename=src.filename,
                        page_number=src.page_number,
                    )
                )
        else:
            if candidate_id not in invalid_ids:
                invalid_ids.append(candidate_id)

    # Sanitize invalid citations from text
    cleaned_answer = raw_answer
    for invalid_id in invalid_ids:
        # Remove invalid token and any double spaces resulting from removal
        cleaned_answer = cleaned_answer.replace(invalid_id, "")

    # Clean up excess whitespace left by removed citations
    cleaned_answer = re.sub(r" +", " ", cleaned_answer).strip()

    return CitationValidationResult(
        cleaned_answer=cleaned_answer,
        validated_citations=validated_citations,
        invalid_source_ids=invalid_ids,
        has_valid_citations=len(validated_citations) > 0,
    )
